/**
 * The translation tables, read out of game/js/i18n.js.
 *
 * Parsed rather than imported: importing it would need a DOM, and the point
 * of this gate is to run without a browser. The file is a plain object
 * literal of single-quoted keys, which is exactly what the rest of the repo
 * writes, so the parse stays honest as long as that holds -- and if it ever
 * stops holding, `tables` comes back empty and every i18n check shouts.
 */
let i18nCache = null;
function i18n() {
  if (i18nCache) return i18nCache;
  const src = text('game/js/i18n.js');
  const tables = {};
  const order = {};
  const codes = [...src.matchAll(/\{\s*code:\s*'(\w+)'/g)].map((m) => m[1]);
  for (const code of codes) {
    const start = src.search(new RegExp(`^  ${code}: \\{$`, 'm'));
    if (start < 0) continue;
    const end = src.indexOf('\n  },', start);
    const body = src.slice(start, end < 0 ? src.length : end);
    const table = {};
    const keys = [];
    // Values may be concatenated across lines: take everything up to the
    // line that starts the next key, or the end of the table.
    const entry = /^\s{4}'([^']+)':\s*([\s\S]*?)(?=\n\s{4}'[^']+':|$)/gm;
    for (const m of body.matchAll(entry)) {
      keys.push(m[1]);
      table[m[1]] = [...m[2].matchAll(/'((?:[^'\\]|\\.)*)'/g)]
        .map((s) => s[1]).join('');
    }
    tables[code] = table;
    order[code] = keys;
  }
  i18nCache = { tables, order };
  return i18nCache;
}

/**
 * Everywhere the game asks for a string.
 *
 * Keys reach `t()` three ways: written out at the call, carried in config as
 * a `nameKey`-style field, or built from a prefix (`t('weather.' + name)`).
 *
 * The two directions need different evidence, so they get different lists.
 * `asked` is only what unmistakably names a key -- a `t()` argument, a
 * `...Key:` field, a `data-i18n` attribute -- because a key that does not
 * exist has to be a real mistake before we call it one. `mentioned` is every
 * string literal in the game, because a key passed through a local helper
 * (`row('records.jobs', …)`) is still a key in use, and calling it dead would
 * delete a string the player can see.
 */
function keyReferences() {
  const asked = [];
  const mentioned = new Set();
  const prefixes = [];
  const table = tableRegion();
  for (const path of GAME_JS) {
    const body = path === 'game/js/i18n.js'
      ? text(path).slice(0, table.start) + text(path).slice(table.end)
      : text(path);
    body.split('\n').forEach((line, i) => {
      const where = `${path}:${i + 1}`;
      for (const m of line.matchAll(/\bt\(\s*'([^']*)'\s*\+/g)) prefixes.push(m[1]);
      for (const m of line.matchAll(/\bfirstTime\(\s*'([^']*)'\s*\+/g)) prefixes.push(m[1]);
      for (const m of line.matchAll(/\bt\(\s*'([^']+)'\s*[,)]/g)) {
        asked.push({ key: m[1], where });
      }
      for (const m of line.matchAll(/\b\w*Key:\s*'([^']+)'/g)) asked.push({ key: m[1], where });
      for (const m of line.matchAll(/'([^']+)'/g)) mentioned.add(m[1]);
    });
  }
  const html = text('game/index.html');
  for (const m of html.matchAll(/data-i18n(?:-html|-aria)?="([^"]+)"/g)) {
    asked.push({ key: m[1], where: 'game/index.html' });
    mentioned.add(m[1]);
  }
  return { asked, mentioned, prefixes };
}

/** Where the STRINGS object starts and ends in i18n.js -- definitions, not uses. */
function tableRegion() {
  const src = text('game/js/i18n.js');
  const start = src.indexOf('const STRINGS = {');
  const end = start < 0 ? -1 : src.indexOf('\n};', start);
  return start < 0 || end < 0 ? { start: 0, end: 0 } : { start, end: end + 3 };
}

/** Parse every path given, write nothing, and say so on the first failure. */
const PY_PARSE = [
  'import sys',
  'for path in sys.argv[1:]:',
  '    with open(path, "rb") as fh:',
  '        compile(fh.read(), path, "exec")',
].join('\n');

/** Run a command; return '' when it succeeds, its complaint when it does not. */
function spawnQuiet(command, args) {
  try {
    execFileSync(command, args, { cwd: ROOT, stdio: 'pipe' });
    return '';
  } catch (err) {
    return ((err.stderr || '') + (err.stdout || '')).toString().trim()
      || `${command} exited ${err.status}`;
  }
}

// --- running ----------------------------------------------------------------

/**
 * Run every check.
 *
 * @returns {Array<{name: string, why: string, ok: boolean, problems: string[]}>}
 */
export function runChecks() {
  return checks.map(({ name, why, run }) => {
    let problems;
    try {
      problems = run();
    } catch (err) {
      problems = [`the check itself failed: ${err.message}`];
    }
    return { name, why, ok: problems.length === 0, problems };
  });
}

/** Repo-relative paths the gate looked at, for the suites to report. */
export function scope() {
  return { files: FILES.length, sources: SOURCE.length, checks: checks.length };
}

if (process.argv[1] && resolve(process.argv[1]) === resolve(fileURLToPath(import.meta.url))) {
  const verbose = process.argv.includes('-v') || process.argv.includes('--verbose');
  const results = runChecks();
  let failed = 0;
  for (const result of results) {
    if (result.ok) {
      console.log(`PASS  ${result.name}`);
      if (verbose) console.log(`      ${result.why}`);
      continue;
    }
    failed += 1;
    console.log(`FAIL  ${result.name}`);
    console.log(`      ${result.why}`);
    for (const problem of result.problems.slice(0, 20)) console.log(`      - ${problem}`);
    const extra = result.problems.length - 20;
    if (extra > 0) console.log(`      - ...and ${extra} more`);
  }
  const { files, sources } = scope();
  console.log(failed
    ? `\n${failed} of ${results.length} checks failed (${files} files, ${sources} sources)`
    : `\nall ${results.length} checks passed (${files} files, ${sources} sources)`);
  process.exit(failed ? 1 : 0);
}
